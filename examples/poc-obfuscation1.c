int
main(
         int                           argc,
         char *                        argv[] )
{
   int               c;
   int               opt_index;
   int               minimal_padding;
   size_t            pos;
   size_t            len;
   size_t            idx;
   size_t            payload_sum;
   size_t            payload_offset;
   size_t            secret_data_len;
   size_t            len_mask;
   size_t            buff_len;
   size_t            buff_size;
   uint8_t *         buff;
   uint8_t           md[TICS_MD_SIZE];
   tics_hmac_t *     hmac;
   const char *      secret_key;
   const char *      secret_data;

   // getopt options
   static const char *  short_opt = "hmqr:Vv";
   static struct option long_opt[] =
   {  {"help",             no_argument,       NULL, 'h' },
      {"quiet",            no_argument,       NULL, 'q' },
      {"silent",           no_argument,       NULL, 'q' },
      {"version",          no_argument,       NULL, 'V' },
      {"verbose",          no_argument,       NULL, 'v' },
      { NULL, 0, NULL, 0 }
   };

   secret_key        = default_key;
   secret_data       = default_dat;
   minimal_padding   = 0;

   while((c = getopt_long(argc, argv, short_opt, long_opt, &opt_index)) != -1)
   {  switch(c)
      {  case -1:       /* no more arguments */
         case 0:        /* long options toggles */
            break;

         case 'h':
            printf("Usage: %s [OPTIONS]\n", PROGRAM_NAME);
            printf("       %s [OPTIONS] [ <secret> [ <key> ]]\n", PROGRAM_NAME);
            printf("OPTIONS:\n");
            printf("  -h, --help                print this help and exit\n");
            printf("  -m                        use minimal padding\n");
            printf("  -r device                 use random device\n");
            printf("  -q, --quiet, --silent     do not print messages\n");
            printf("  -V, --version             print version number and exit\n");
            printf("  -v, --verbose             print verbose messages\n");
            printf("\n");
            return(0);

         case 'm':
            minimal_padding = 1;
            break;

         case 'r':
            if ((random_fd = open(optarg, O_RDONLY)) == -1)
            {  fprintf(stderr, "%s: %s: %s\n", PROGRAM_NAME, optarg, strerror(errno));
               return(1);
            };
            break;

         case 'q':
            break;

         case 'V':
            printf("%s (%s) %s\n", PROGRAM_NAME, PACKAGE_NAME, PACKAGE_VERSION);
            printf("Written by David M. Syzdek.\n");
            return(0);

         case 'v':
            break;

         case '?':
            fprintf(stderr, "Try `%s --help' for more information.\n", PROGRAM_NAME);
            return(1);

         default:
            fprintf(stderr, "%s: unrecognized option `--%c'\n", PROGRAM_NAME, c);
            fprintf(stderr, "Try `%s --help' for more information.\n", PROGRAM_NAME);
            return(1);
      };
   };
   if ((optind+2) < argc)
   {  fprintf(stderr, "%s: unrecognized argument `%s'\n", PROGRAM_NAME, argv[optind+2]);
      fprintf(stderr, "Try `%s --help' for more information.\n", PROGRAM_NAME);
      return(1);
   };

   if (optind < argc)
      secret_data = argv[optind];
   if ((optind+1) < argc)
      secret_key = argv[optind+1];

   secret_data_len   = strlen(secret_data);
   buff_len          = 0;

   // calculate payload data length mask
   len_mask = 0x10000;
   while((secret_data_len < len_mask) && (len_mask >= 64))
      len_mask >>= 1;
   len_mask <<= 1;
   len_mask--;

   // allocate buffer
   buff_size = len_mask + 1 + 256;
   if ((minimal_padding))
   {  buff_size = 64 - (strlen(secret_data) % 64);
      buff_size += strlen(secret_data) + 256;
   };
   if ((buff = malloc(buff_size)) == NULL)
   {  fprintf(stderr, "%s: out of virtual memory\n", PROGRAM_NAME);
      return(1);
   };
   memset(buff, 0, buff_size);

   // copy random data as salt into buffer
   my_rndcpy(&buff[buff_len], 64);
   buff_len += 64;

   // copy random data as offset seed into buffer
   my_rndcpy(&buff[buff_len], 64);
   buff_len += 64;

   // calculate payload offset
   for(pos = 64, payload_sum = 0; (pos < 128); pos++)
      payload_sum += (size_t)buff[pos];
   payload_offset = payload_sum % 62;

   // copy random data into buffer to padd payload offset
   my_rndcpy(&buff[buff_len], payload_offset);
   buff_len += payload_offset;

   // pad secret length
   my_rndcpy(&buff[buff_len], 2);
   buff[buff_len]    = (uint8_t)((~len_mask >> 8) & buff[buff_len]);
   buff[buff_len++] |= (uint8_t)((secret_data_len & len_mask) >> 8);
   buff[buff_len]    = (uint8_t)(~len_mask & buff[buff_len]);
   buff[buff_len++] |= (uint8_t)(secret_data_len & len_mask);

   // copy secret into buffer
   memcpy(&buff[buff_len], secret_data, secret_data_len);
   buff_len += secret_data_len;

   // pad secret to nearest 64 bytes
   len = 64 - (buff_len % 64);
   my_rndcpy(&buff[buff_len], len);
   buff_len += len;

   // copy random data as payload info buffer until payload is at least 128 bytes
   while (buff_len < buff_size-64)
   {  my_rndcpy(&buff[buff_len], 64);
      buff_len += 64;
   };

   // calculate SHA-512 hash of data and copy to buffer
   tics_hash(TICS_HASH_SHA512, buff, buff_len, &buff[buff_len], buff_size-buff_len);
   buff_len += 64;

   // obfuscate data
   tics_hmac_init(&hmac, TICS_HASH_SHA512, secret_key, strlen(secret_key));
   tics_hmac_update(hmac, buff, 64);
   for(idx = 64; (idx < buff_len); idx += 64)
   {  tics_hmac_result(hmac, md, sizeof(md));
      tics_hmac_update(hmac, &buff[idx], 64);
      for(pos = 0; (pos < 64); pos++)
         buff[idx+pos] ^= md[pos];
   };
   tics_hmac_free(hmac);

   if ((my_summary(secret_key, secret_data, buff, buff_len)))
   {  free(buff);
      return(1);
   };

   free(buff);

   if (random_fd != -1)
      close(random_fd);

   return( 0 );
}


